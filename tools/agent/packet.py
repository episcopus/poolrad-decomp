#!/usr/bin/env python3
"""packet.py: write a work packet for a unit or routine (SPEC 9.3).

Phase 1 packet: inventory, callees/callers summary, strings, whitepaper pointers.
(Full disassembly + Ghidra decomp arrive as the oracle/hybrid land in P2/P3.)

Usage:
  make packet UNIT=ovl00
  make packet FN=ovl00:00AC
"""
from __future__ import annotations

import argparse
import json
import os
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "re"))
from mzutil import read_mz  # noqa: E402


def load_routines(path: Path) -> list[dict]:
    out, cur = [], None
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        s = line.strip()
        if s == "[[routine]]":
            if cur:
                out.append(cur)
            cur = {}
            continue
        if cur is None or not s or s.startswith("#"):
            continue
        m = re.match(r'^(\w+)\s*=\s*(.+)$', s)
        if not m:
            continue
        k, raw = m.group(1), m.group(2).strip()
        if raw.startswith('"') and raw.endswith('"'):
            cur[k] = raw[1:-1]
        else:
            try:
                cur[k] = int(raw, 0)
            except ValueError:
                cur[k] = raw
    if cur:
        out.append(cur)
    return out


def unit_meta(units_text: str, uid: str) -> dict:
    parts = re.split(r"(?=\[\[resident\]\]|\[\[overlay\]\])", units_text)
    for part in parts:
        if re.search(r'^id\s*=\s*"%s"' % re.escape(uid), part, re.M):
            meta = {"id": uid}
            for m in re.finditer(r'^(\w+)\s*=\s*"([^"]*)"', part, re.M):
                meta[m.group(1)] = m.group(2)
            for m in re.finditer(r"^(\w+)\s*=\s*(\d+)", part, re.M):
                meta[m.group(1)] = int(m.group(2))
            return meta
    return {"id": uid}


def overlay_strings(uid: str) -> list[str]:
    m = re.match(r"ovl(\d+)$", uid)
    if not m:
        return []
    path = ROOT / "build/re/overlays" / ("ovl%02d.bin" % int(m.group(1)))
    if not path.exists():
        return []
    blob = path.read_bytes()
    out = []
    i = 0
    while i < len(blob):
        if i + 1 < len(blob) and 6 <= blob[i] <= 80:
            n = blob[i]
            s = blob[i + 1 : i + 1 + n]
            if len(s) == n and all(32 <= b < 127 for b in s):
                out.append(s.decode("ascii"))
                i += 1 + n
                continue
        i += 1
    return out[:40]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--unit", default=os.environ.get("UNIT", ""))
    ap.add_argument("--fn", default=os.environ.get("FN", ""))
    args = ap.parse_args(argv[1:])
    # also accept UNIT= / FN= positional-style from make
    for a in argv[1:]:
        if a.startswith("UNIT="):
            args.unit = a.split("=", 1)[1]
        if a.startswith("FN="):
            args.fn = a.split("=", 1)[1]

    uid = args.unit
    fn = args.fn
    if fn and not uid:
        if fn.startswith("ovl"):
            uid = fn.split(":")[0]
        else:
            # resident: look up unit from symbols
            for r in load_routines(ROOT / "re/symbols.toml"):
                if r.get("id") == fn or r.get("addr") == fn:
                    uid = str(r.get("unit", ""))
                    break
    if not uid and not fn:
        print("packet: need UNIT=<id> or FN=<id>", file=sys.stderr)
        return 2

    routines = [r for r in load_routines(ROOT / "re/symbols.toml") if r.get("unit") == uid]
    if fn:
        routines = [r for r in routines if r.get("id") == fn or r.get("addr") == fn] or routines
    units_text = (ROOT / "re/units.toml").read_text()
    meta = unit_meta(units_text, uid or "?")
    out_dir = ROOT / "build" / "packets"
    out_dir.mkdir(parents=True, exist_ok=True)
    key = fn.replace(":", "_") if fn else uid
    out_path = out_dir / ("%s.md" % key)

    lines = [
        "# Work packet: %s" % (fn or uid),
        "",
        "Generated by `tools/agent/packet.py` (SPEC 9.3). Ghidra decompilation is a hint only.",
        "",
        "## Unit",
        "",
        "| Field | Value |",
        "|---|---|",
        "| id | %s |" % meta.get("id"),
        "| name | %s |" % meta.get("name"),
        "| kind | %s |" % meta.get("kind", ""),
        "| init | %s |" % meta.get("init", meta.get("init_entry", "")),
        "| code_bytes | %s |" % meta.get("code_bytes", ""),
        "| evidence | %s |" % meta.get("evidence", ""),
        "",
        "## Routines in scope (%d)" % len(routines),
        "",
        "| id | size | name | level | notes |",
        "|---|---:|---|---|---|",
    ]
    for r in sorted(routines, key=lambda x: str(x.get("id"))):
        lines.append(
            "| %s | %s | %s | %s | %s |"
            % (
                r.get("id"),
                r.get("size"),
                r.get("name"),
                r.get("level"),
                str(r.get("notes", ""))[:60],
            )
        )

    strs = overlay_strings(uid or "")
    if strs:
        lines += ["", "## Strings (sample)", ""]
        for s in strs:
            lines.append("- `%s`" % s.replace("`", "'"))

    lines += [
        "",
        "## Whitepaper",
        "",
        "- `docs/design/WHITEPAPER.md` sections 2 (build), 3 (architecture / calling conventions)",
        "- Prior art (read only): `docs/reference/prior-art.md`",
        "",
        "## Next steps (playbook 30, after P3)",
        "",
        "1. Confirm signatures in `re/symbols.toml`",
        "2. Lift leaves first; `make fuzz FN=...`",
        "3. Commit per routine; request review when the unit is L2",
        "",
    ]
    out_path.write_text("\n".join(lines))
    print("packet: wrote %s (%d routines)" % (out_path, len(routines)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
