#!/usr/bin/env python3
"""status.py: regenerate work/status.md from re/ inventory (SPEC 9.4).

Usage:
  python3 tools/agent/status.py [-o work/status.md]
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def parse_routines(path: Path) -> list[dict]:
    if not path.exists():
        return []
    out, cur = [], None
    for line in path.read_text().splitlines():
        s = line.strip()
        if s == "[[routine]]":
            if cur:
                out.append(cur)
            cur = {}
            continue
        if cur is None or not s or s.startswith("#"):
            continue
        m = re.match(r'^([A-Za-z0-9_]+)\s*=\s*(.+)$', s)
        if not m:
            continue
        k, raw = m.group(1), m.group(2).strip()
        if raw.startswith('"') and raw.endswith('"'):
            cur[k] = raw[1:-1]
        else:
            try:
                cur[k] = int(raw, 0)
            except ValueError:
                cur[k] = raw
    if cur:
        out.append(cur)
    return out


def parse_units(path: Path) -> tuple[list[dict], list[dict]]:
    res, ovl, cur, kind = [], [], None, None
    if not path.exists():
        return res, ovl
    for line in path.read_text().splitlines():
        s = line.strip()
        if s == "[[resident]]":
            if cur:
                (res if kind == "resident" else ovl).append(cur)
            cur, kind = {}, "resident"
            continue
        if s == "[[overlay]]":
            if cur:
                (res if kind == "resident" else ovl).append(cur)
            cur, kind = {}, "overlay"
            continue
        if cur is None or not s or s.startswith("#"):
            continue
        m = re.match(r'^([A-Za-z0-9_]+)\s*=\s*(.+)$', s)
        if not m:
            continue
        k, raw = m.group(1), m.group(2).strip()
        if raw.startswith('"') and raw.endswith('"'):
            cur[k] = raw[1:-1]
        else:
            try:
                cur[k] = int(raw, 0)
            except ValueError:
                cur[k] = raw
    if cur:
        (res if kind == "resident" else ovl).append(cur)
    return res, ovl


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("-o", "--output", default=str(ROOT / "work/status.md"))
    args = ap.parse_args(argv[1:])

    routines = parse_routines(ROOT / "re/symbols.toml")
    residents, overlays = parse_units(ROOT / "re/units.toml")
    # drop accidental comment-only "resident" ghosts (no id)
    residents = [r for r in residents if r.get("id")]
    overlays = [o for o in overlays if o.get("id")]
    levels = Counter(str(r.get("level", "none")) for r in routines)
    by_unit = Counter(str(r.get("unit", "?")) for r in routines)
    named = sum(
        1
        for r in routines
        if r.get("name")
        and not re.search(r"_fn_[0-9A-Fa-f]{4}$", str(r.get("name")))
        and not re.search(r"_e\d+$", str(r.get("name")))
    )
    named_rtl = sum(
        1
        for r in routines
        if str(r.get("name", "")).startswith(("System_", "Crt_", "Overlay_", "Dos_"))
    )
    res_init = [r for r in residents if r.get("init")]
    code_bytes = sum(int(u.get("code_bytes") or 0) for u in residents + overlays)
    routine_bytes = sum(int(r.get("size") or 0) for r in routines)

    scripts = sorted(p.stem for p in (ROOT / "tests/sessions").glob("*.keys"))
    goldens = [n for n in scripts if (ROOT / "tests/sessions/golden" / n / "golden.json").exists()]
    today = dt.date.today().isoformat()
    lines = [
        "# Project status",
        "",
        "Generated by `make status` (%s)." % today,
        "",
        "## Phase",
        "",
        "**P1 Map: complete** when `make p1-check` is green. P0 bootstrap is done.",
        "",
        "| P1 exit criterion | State |",
        "|---|---|",
        "| Ghidra project via `make ghidra` | tool + `build/ghidra/` (regenerate after map) |",
        "| 48 units with code ranges in `re/units.toml` | %d init-chain resident + %d overlay = %d; plus %d runtime units without init (Dos, Overlay) |"
        % (len(res_init), len(overlays), len(res_init) + len(overlays), len(residents) - len(res_init)),
        "| Every routine listed in `re/symbols.toml` | %d routines (sum sizes %d; unit code_bytes %d) |"
        % (len(routines), routine_bytes, code_bytes),
        "| RTL identified and named | System/Crt/Dos/Overlay byte-matched to TP 6.0; %d RTL-prefixed names |" % named_rtl,
        "| TP version pinned or bounded | **pinned**: Turbo Pascal 6.0, June 1991 release (`make tp-compare`, WHITEPAPER 2.2) |",
        "| DGROUP map started | `re/dseg.toml` |",
        "| Calling convention samples | whitepaper section 3.4 |",
        "| Initial names from strings / prior art | overlay names in `re/units.toml` |",
        "| Gate | run `make p1-check` |",
        "",
        "**P2 Oracle and data**: goldens recorded for %d of %d session scripts (%s)." % (len(goldens), len(scripts), ", ".join(goldens) or "none"),
        "",
        "| P2 exit criterion | Gate |",
        "|---|---|",
        "| Oracle boots to title and through character creation from a key script, twice identically | `make golden` (records each session from two runs that must match), `make golden CHECK=1` |",
        "| Hybrid timing (decision 2026-10-10: exact time, no masks) | `tools/oracle/timing.py`, `make oracle-timing`, `tests/unit/test_exact_time.py` |",
        "| Screenshots match DOSBox-X | `make oracle-dosbox` |",
        "| DAX, map and ECL decoders with tests over all files | `make dax`, `make test` |",
        "| First goldens recorded | `tests/sessions/golden/` |",
        "",
        "**P3 Runtime and skeleton**: gate is `make check`.",
        "",
        "| P3 exit criterion | State |",
        "|---|---|",
        "| Memory model spike (SPEC 7.3) | `System_Move`, `System_FillChar`, `System_Random` at L2; `G` is the DGROUP image at linear 0x1C7C0; hybrid `FP()` addresses guest RAM |",
        "| `src/rtl` with tests | Move, FillChar, Random, Randomize packing; `tests/unit/test_p3_spike.py` |",
        "| SDL3 host platform | `make host` -> `build/host/poolrad` (BIOS keys, PIT period, framebuffer) |",
        "| Hybrid library in the oracle | `make hybrid`; `tools/oracle/hybrid.py` |",
        "| `make check` | build, lint, unit tests, fuzz, sessions (Move+FillChar; Random stays L2 until the spinner decision below) |",
        "",
        "## Inventory",
        "",
        "| | Count |",
        "|---|---:|",
        "| Units | %d |" % (len(residents) + len(overlays)),
        "| Routines | %d |" % len(routines),
        "| Routines with non-provisional names | %d |" % named,
        "| RTL-prefixed routine names | %d |" % named_rtl,
        "| Unit code_bytes (declared) | %d |" % code_bytes,
        "| Sum of routine sizes | %d |" % routine_bytes,
        "",
        "### Routines by level",
        "",
        "| Level | Count |",
        "|---|---:|",
    ]
    for lv in ("none", "L0", "L1", "L2", "L3", "M"):
        if levels.get(lv):
            lines.append("| %s | %d |" % (lv, levels[lv]))
    for lv, n in sorted(levels.items()):
        if lv not in ("none", "L0", "L1", "L2", "L3", "M"):
            lines.append("| %s | %d |" % (lv, n))

    lines += [
        "",
        "### Top units by routine count",
        "",
        "| Unit | Routines |",
        "|---|---:|",
    ]
    for uid, n in by_unit.most_common(15):
        lines.append("| %s | %d |" % (uid, n))

    lifted = [r for r in routines if str(r.get("level", "none")) not in ("", "none")]
    if not lifted:
        verification = "No routines lifted yet (all levels `none`)."
    else:
        shown = ", ".join("%s %s (%s)" % (r.get("name", r.get("id")), r.get("level"), r.get("id"))
                          for r in sorted(lifted, key=lambda r: str(r.get("id"))))
        verification = "%d routines above `none`: %s." % (len(lifted), shown)
    lines += [
        "",
        "## Verification",
        "",
        verification,
        "",
        "## Blockers and decisions waiting for the human",
        "",
        "- Platform waits (decided 2026-10-10): `src/platform/platform.h` has input, time, entropy, timer, sound and video present (WHITEPAPER 5.14). Files and the heap suballocator arrive with the first lifted unit that needs them. Lifters of the routines in `build/re/timing-scan.md` use the waits, never a spin on a poll.",
        "- Random in a golden session (WHITEPAPER appendix C): `System_Random` is L2 by fuzz. Putting it in C during `boot-title` moves one title-screen `shot` by a single spinner step (5022 vs 5021 calls). `make check` therefore replays sessions with Move and FillChar only. Whether the golden comparison gains a spinner tolerance is still open.",
        "- Canonical state and the stack (WHITEPAPER appendix C): hybrid runs reproduce time, screens and Random exactly (`timing.py`), but the stack segment differs (replaced routines push no frames). Goldens carry `canonical` and `canonical_nostack`. Decide whether `re/state.toml` defines the stack as out of the canonical state before L3 on hybrids; until then hybrid runs compare `canonical_nostack`.",
        "- `re/units.toml` lists units found through the init chain plus the two runtime units without init; game units without an initialisation part are still invisible (WHITEPAPER 2.2).",
        "",
        "## Toolchain",
        "",
        "| Tool | Pin | Command |",
        "|---|---|---|",
        "| Turbo Pascal compiler (reference, never committed) | 6.0, June 1991 release (`tools/re/tp_toolchain.toml`) | `make tp-install`, `make tpc SRC=...` |",
        "| Runtime byte comparison | System/Crt/Dos/Overlay match | `make tp-compare` |",
        "| Headless DOS emulator | emu2 (commit in `tools/setup/build-emu2.sh`) | `make emu2` |",
        "",
    ]
    Path(args.output).write_text("\n".join(lines))
    print("status: %d routines, %d units -> %s" % (len(routines), len(residents) + len(overlays), args.output))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
