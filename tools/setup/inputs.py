#!/usr/bin/env python3
"""inputs.py: pin and verify the original game files in poolrad/.

  python3 tools/setup/inputs.py --check   # verify against re/inputs.toml (default)
  python3 tools/setup/inputs.py --write   # (re)write re/inputs.toml; humans only, see AGENTS.md rule 6
"""
import argparse, hashlib, os, sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    tomllib = None

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GAME = os.path.join(ROOT, "poolrad")
PIN = os.path.join(ROOT, "re", "inputs.toml")
# Files that are part of the original game (analysis aids such as IDA databases are not pinned).
SKIP_EXT = {".id0", ".id1", ".nam", ".til", ".idb", ".md", ".pdf", ".code-workspace"}
SKIP_NAMES = {"exepack.exe", "upx.exe", "CFG.C", "CFG.EXE", "POOL.BAT", "POOL.CFG", ".DS_Store"}


def files():
    for dp, dn, fn in os.walk(GAME):
        dn.sort()
        for f in sorted(fn):
            if f in SKIP_NAMES or os.path.splitext(f)[1].lower() in SKIP_EXT:
                continue
            p = os.path.join(dp, f)
            yield os.path.relpath(p, ROOT).replace(os.sep, "/"), p


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def parse_pins(text):
    if tomllib:
        return {k: v["sha256"] for k, v in tomllib.loads(text).get("file", {}).items()}
    pins, cur = {}, None  # minimal fallback parser for this file's own format
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('[file."'):
            cur = line[7:-2]
        elif line.startswith("sha256") and cur:
            pins[cur] = line.split('"')[1]
    return pins


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if not os.path.isdir(GAME):
        print("missing: poolrad/ (the original game files)")
        return 1
    if a.write:
        out = ["# Pinned original inputs. Generated by tools/setup/inputs.py --write.",
               "# Changing this file changes the target of the whole project (AGENTS.md rule 6).", ""]
        for rel, p in files():
            out += ['[file."%s"]' % rel, "bytes = %d" % os.path.getsize(p), 'sha256 = "%s"' % sha(p), ""]
        open(PIN, "w").write("\n".join(out))
        print("wrote", os.path.relpath(PIN, ROOT))
        return 0
    if not os.path.exists(PIN):
        print("missing: re/inputs.toml (run tools/setup/inputs.py --write once)")
        return 1
    pins = parse_pins(open(PIN).read())
    seen, bad = set(), 0
    for rel, p in files():
        seen.add(rel)
        if rel not in pins:
            print("extra   " + rel); bad += 1
        elif sha(p) != pins[rel]:
            print("CHANGED " + rel); bad += 1
    for rel in sorted(set(pins) - seen):
        print("MISSING " + rel); bad += 1
    print("inputs: %d files pinned, %s" % (len(pins), "OK" if not bad else "%d problems" % bad))
    return 0 if not bad else 1


if __name__ == "__main__":
    sys.exit(main())
