#!/bin/sh
# setup-macos.sh: install what the Pool of Radiance decompilation needs on macOS (Apple Silicon or Intel).
# Idempotent: re-running only installs what is missing. Nothing is installed into poolrad/.
#
#   sh tools/setup/setup-macos.sh [--dry-run] [--with-ghidra] [--with-coco] [--with-dos]
#
#   (default)       Homebrew packages for phases 0 to 3, Python environment (uv sync)
#   --with-ghidra   download Ghidra 12.1.4 into ~/opt and write tools/setup/env.local.sh
#   --with-coco     LWTOOLS and XRoar for the CoCo 3 work (phase 7); CMOC is built from source
#   --with-dos      checks for a container runtime for the Open Watcom DOS build (phase 8)
set -eu

GHIDRA_VERSION=12.1.4
GHIDRA_ZIP=ghidra_12.1.4_PUBLIC_20260921.zip
GHIDRA_URL="https://github.com/NationalSecurityAgency/ghidra/releases/download/Ghidra_${GHIDRA_VERSION}_build/${GHIDRA_ZIP}"
OPT_DIR="${OPT_DIR:-$HOME/opt}"

DRY=0; WITH_GHIDRA=0; WITH_COCO=0; WITH_DOS=0
for a in "$@"; do
  case "$a" in
    --dry-run) DRY=1 ;;
    --with-ghidra) WITH_GHIDRA=1 ;;
    --with-coco) WITH_COCO=1 ;;
    --with-dos) WITH_DOS=1 ;;
    -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
    *) echo "unknown option: $a"; exit 2 ;;
  esac
done

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
run() { echo "+ $*"; [ $DRY -eq 1 ] || "$@"; }
say() { echo "== $*"; }

if [ "$(uname -s)" != "Darwin" ]; then
  echo "This script is for macOS. On Linux see docs/setup/SETUP-macos.md, section 'Linux'."; exit 1
fi

say "Xcode command line tools"
if xcode-select -p >/dev/null 2>&1; then echo "ok: $(xcode-select -p)"; else run xcode-select --install; echo "Finish the installer dialog, then re-run this script."; exit 1; fi

say "Homebrew"
if ! command -v brew >/dev/null 2>&1; then
  echo "Homebrew is not installed. Install it from https://brew.sh (it needs your password), then re-run."; exit 1
fi
echo "ok: $(brew --version | head -1)"

brew_install() {
  for f in "$@"; do
    if brew list --formula "$f" >/dev/null 2>&1; then echo "ok: $f"; else run brew install "$f"; fi
  done
}

say "Packages for phases 0 to 3"
#  uv: Python and tool dependencies; cmake/ninja/pkgconf/sdl3: native C build; dosbox-x: oracle cross-check;
#  openjdk@21: Ghidra 12 needs Java 21 or later.
brew_install uv cmake ninja pkgconf sdl3 dosbox-x openjdk@21

say "Python environment (.venv via uv)"
run uv sync --python 3.12

JAVA_HOME_GUESS="$(brew --prefix)/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home"
GHIDRA_DIR="$OPT_DIR/ghidra_${GHIDRA_VERSION}_PUBLIC"

if [ $WITH_GHIDRA -eq 1 ]; then
  say "Ghidra $GHIDRA_VERSION"
  if [ -x "$GHIDRA_DIR/support/analyzeHeadless" ]; then
    echo "ok: $GHIDRA_DIR"
  else
    run mkdir -p "$OPT_DIR"
    run curl -L --fail -o "$OPT_DIR/$GHIDRA_ZIP" "$GHIDRA_URL"
    run unzip -q -o "$OPT_DIR/$GHIDRA_ZIP" -d "$OPT_DIR"
    run rm -f "$OPT_DIR/$GHIDRA_ZIP"
  fi
fi

say "Environment file (tools/setup/env.local.sh, not committed)"
if [ $DRY -eq 0 ]; then
  {
    echo "# Generated by tools/setup/setup-macos.sh. Source it: . tools/setup/env.local.sh"
    echo "export JAVA_HOME=\"$JAVA_HOME_GUESS\""
    echo "export PATH=\"\$JAVA_HOME/bin:\$PATH\""
    if [ -d "$GHIDRA_DIR" ]; then echo "export GHIDRA_INSTALL_DIR=\"$GHIDRA_DIR\""; fi
  } > tools/setup/env.local.sh
  echo "wrote tools/setup/env.local.sh"
else
  echo "(dry run: would write tools/setup/env.local.sh)"
fi

if [ $WITH_COCO -eq 1 ]; then
  say "CoCo 3 tools (phase 7)"
  brew_install lwtools xroar
  echo "CMOC has no Homebrew formula: build it from source (http://sarrazip.com/dev/cmoc.html) after lwtools:"
  echo "  ./configure --prefix=\$HOME/opt/cmoc && make && make install"
  echo "Note: the lwtools formula is marked deprecated in Homebrew (checksum mismatch); if it fails, build"
  echo "LWTOOLS from source (http://www.lwtools.ca)."
fi

if [ $WITH_DOS -eq 1 ]; then
  say "DOS build (phase 8)"
  if command -v docker >/dev/null 2>&1; then echo "ok: $(docker --version)"; else
    echo "Install a container runtime (OrbStack or Docker Desktop). Open Watcom v2 ships Linux x64 and DOS hosts,"
    echo "not macOS, so the DOS build runs it in a linux/amd64 container (docs/setup/SETUP-macos.md)."
  fi
fi

say "Next"
echo "  . tools/setup/env.local.sh && make doctor"
