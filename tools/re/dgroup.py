POOLVARS = ROOT / "src/POOLVARS.PAS"
DGROUP_BASE = tp.DGROUP_PARA * 16
FIRST_CONST = 0x0002             # Turbo Pascal's first typed constant of a program (DS:0000 holds its own word)
CONST_END = 0x43DC               # the game's typed constants end here; the Overlay unit's own (OvrResult ..) follow
SYSTEM_BLOCK = 0x43EC            # OvrCodeList: the Overlay and System variable blocks follow the constants
VARS_START = 0x442E              # the end of System's block (FileMode, Test8087)
LAYOUT_BEGIN = "{ ---- DGROUP layout, generated by tools/re/dgroup.py (playbook 50): do not reorder ---- }"
LIBRARY_VARS = 0x84F0            # the first Crt variable (CheckBreak): the game's variables end here
INPUT_VAR = 0x8508               # System's Input: the library variables of Crt end here


class DGroupError(Exception):
    pass


# --- tokens ------------------------------------------------------------------------------------------
TOKEN = re.compile(r"\{[^}]*\}|'(?:[^']|'')*'|#\d+|\$[0-9A-Fa-f]+|\d+|\.\.|[A-Za-z_]\w*|\S")


def tokens(text: str) -> list[str]:
    out = []
    for m in TOKEN.finditer(text):
        t = m.group(0)
        if t.startswith("{"):
            continue
        out.append(t)
    return out


# --- the declarations of POOLVARS --------------------------------------------------------------------
class Item:
    def __init__(self, names, type_text, absolute, comments, trailing):
        self.names: list[str] = names
        self.type_text: str = type_text
        self.absolute: str | None = absolute
        self.comments: list[str] = comments      # the comment blocks written before the declaration
        self.trailing: str = trailing            # the comment after it on the same line
        self.offset: int | None = None
        self.size: int | None = None

    @property
    def name(self) -> str:
        return self.names[0]


def split_poolvars(text: str):
    """(head: through the `var` keyword line, var section, tail: from `implementation`)."""
    m = re.search(r"^var\s*$", text, re.M)
    t = re.search(r"^implementation\b", text, re.M)
    if not m or not t:
        raise DGroupError("POOLVARS.PAS: no `var` section or no `implementation`")
    return text[:m.start()], text[m.end():t.start()], text[t.start():]


def parse_var_section(text: str) -> list[Item]:
    items: list[Item] = []
    pending: list[str] = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c.isspace():
            i += 1
            continue
        if c == "{":
            j = text.index("}", i)
            pending.append(text[i:j + 1])
            i = j + 1
            continue
        j = i
        while j < n:
            if text[j] == "{":
                j = text.index("}", j) + 1
                continue
            if text[j] == ";":
                break
            j += 1
        decl = re.sub(r"\{[^}]*\}", " ", text[i:j])
        decl = " ".join(decl.split())
        i = j + 1
        trailing = ""
        k = i
        while k < n and text[k] in " \t":
            k += 1
        if k < n and text[k] == "{":
            e = text.index("}", k)
            if "\n" not in text[i:e]:
                trailing = text[k:e + 1]
                i = e + 1
        m = re.match(r"^([\w\s,]+?)\s*:\s*(.+?)(?:\s+absolute\s+(\w+))?$", decl)
        if not m:
            raise DGroupError("cannot read the declaration: %r" % decl)
        names = [x.strip() for x in m.group(1).split(",")]
        items.append(Item(names, m.group(2).strip(), m.group(3), pending, trailing))
        pending = []
    if pending:
        raise DGroupError("comments after the last declaration: %r" % pending[0][:60])
    return items


# --- types -------------------------------------------------------------------------------------------
SCALARS = {"BYTE": (1, False), "SHORTINT": (1, True), "WORD": (2, False), "INTEGER": (2, True),
           "LONGINT": (4, True), "BOOLEAN": (1, False), "CHAR": (1, False)}


class Types:
    """The type section of POOLVARS and its named constants: what the literal emitter needs."""

    def __init__(self, head: str):
        self.named: dict[str, list[str]] = {}       # type name (upper) -> tokens of its definition
        self.consts: dict[str, int] = {}
        self._read(head)

    def _read(self, head: str) -> None:
        m = re.search(r"^type\b", head, re.M | re.I)
        c = re.search(r"^const\b", head, re.M | re.I)
        if m:
            seg = head[m.end():c.start() if c else len(head)]
            toks = tokens(seg)
            i = 0
            while i < len(toks):
                if i + 1 < len(toks) and toks[i + 1] == "=":
                    name = toks[i]
                    j = i + 2
                    depth = 0
                    while j < len(toks):
                        t = toks[j].upper()
                        if t in ("RECORD", "CASE"):
                            depth += 1 if t == "RECORD" else 0
                        if t == "END":
                            depth -= 1
                        if toks[j] == ";" and depth <= 0:
                            break
                        j += 1
                    self.named[name.upper()] = toks[i + 2:j]
                    i = j + 1
                else:
                    i += 1
        if c:
            toks = tokens(head[c.end():])
            i = 0
            while i + 3 < len(toks):
                if toks[i + 1] == "=" and toks[i + 3] == ";" or toks[i + 1] == "=" and toks[i + 2] == "-":
                    try:
                        j = toks.index(";", i)
                        self.consts[toks[i].upper()] = self.eval(toks[i + 2:j])
                        i = j + 1
                        continue
                    except (ValueError, DGroupError):
                        pass
                i += 1

    def eval(self, toks: list[str]) -> int:
        """A constant expression of integers, `$` hex, characters (#n, 'c'), names, + and -."""
        total, sign, i = 0, 1, 0
        if not toks:
            raise DGroupError("empty expression")
        while i < len(toks):
            t = toks[i]
            if t == "+":
                sign = 1
            elif t == "-":
                sign = -sign if i == 0 else -1
            else:
                if t.startswith("$"):
                    v = int(t[1:], 16)
                elif t.isdigit():
                    v = int(t)
                elif t.startswith("#"):
                    v = int(t[1:])
                elif t.startswith("'") and len(t) == 3:
                    v = ord(t[1])
                elif t.upper() in self.consts:
                    v = self.consts[t.upper()]
                else:
                    raise DGroupError("unknown constant %r" % t)
                total += sign * v
                sign = 1
            i += 1
        return total


class Parser:
    def __init__(self, types: Types, toks: list[str]):
        self.types, self.t, self.i = types, toks, 0

    def peek(self) -> str:
        return self.t[self.i] if self.i < len(self.t) else ""

    def take(self, want: str | None = None) -> str:
        tok = self.peek()
        if want is not None and tok.upper() != want.upper():
            raise DGroupError("expected %r, found %r" % (want, tok))
        self.i += 1
        return tok

    def expr_until(self, stops: tuple[str, ...]) -> list[str]:
        out, depth = [], 0
        while self.i < len(self.t):
            t = self.t[self.i]
            if depth == 0 and t.upper() in stops:
                break
            if t == "(":
                depth += 1
            if t == ")":
                depth -= 1
            out.append(t)
            self.i += 1
        return out

    def type(self) -> dict:
        tok = self.peek()
        up = tok.upper()
        if up == "PACKED":
            self.take()
            return self.type()
        if up == "STRING":
            self.take()
            if self.peek() == "[":
                self.take()
                n = self.types.eval(self.expr_until(("]",)))
                self.take("]")
                return {"k": "string", "n": n}
            return {"k": "string", "n": 255}
        if up == "ARRAY":
            self.take()
            self.take("[")
            dims = []
            while True:
                toks = self.expr_until((",", "]"))
                dims.append(self.range_of(toks))
                if self.peek() == ",":
                    self.take()
                    continue
                break
            self.take("]")
            self.take("OF")
            elem = self.type()
            for lo, hi in reversed(dims):
                elem = {"k": "array", "lo": lo, "hi": hi, "elem": elem}
            return elem
        if up == "RECORD":
            self.take()
            fields = []
            while self.peek().upper() != "END":
                if self.peek().upper() == "CASE":
                    return {"k": "unsup", "why": "variant record"}
                names = [self.take()]
                while self.peek() == ",":
                    self.take()
                    names.append(self.take())
                self.take(":")
                ft = self.type()
                for nm in names:
                    fields.append((nm, ft))
                if self.peek() == ";":
                    self.take()
            self.take("END")
            return {"k": "record", "fields": fields}
        if up == "SET":
            self.take()
            self.take("OF")
            toks = self.expr_until((";",))
            lo, hi = self.range_of(toks)
            return {"k": "set", "lo": lo, "hi": hi}
        if tok == "^":
            self.take()
            self.take()
            return {"k": "ptr"}
        if tok == "(":
            toks = self.expr_until((";",))
            return {"k": "enum", "n": len([x for x in toks if x not in "(),"])}
        toks = self.expr_until((";",))
        if ".." in toks:
            return {"k": "sub", **dict(zip(("lo", "hi"), self.range_of(toks)))}
        if len(toks) == 1:
            return self.named(toks[0])
        raise DGroupError("cannot read the type %r" % " ".join(toks))

    def range_of(self, toks: list[str]) -> tuple[int, int]:
        if ".." in toks:
            k = toks.index("..")
            return self.types.eval(toks[:k]), self.types.eval(toks[k + 1:])
        if len(toks) == 1:
            up = toks[0].upper()
            if up == "BOOLEAN":
                return 0, 1
            if up == "CHAR":
                return 0, 255
            if up == "BYTE":
                return 0, 255
            d = self.types.named.get(up)
            if d:
                sub = Parser(self.types, d).type()
                if sub["k"] == "sub":
                    return sub["lo"], sub["hi"]
                if sub["k"] == "enum":
                    return 0, sub["n"] - 1
        raise DGroupError("cannot read the range %r" % " ".join(toks))

    def named(self, name: str) -> dict:
        up = name.upper()
        if up in SCALARS:
            size, signed = SCALARS[up]
            return {"k": {"BOOLEAN": "bool", "CHAR": "char"}.get(up, "int"), "size": size, "signed": signed}
        if up == "POINTER":
            return {"k": "ptr"}
        d = self.types.named.get(up)
        if d is None:
            return {"k": "unsup", "why": "type %s" % name}
        t = Parser(self.types, d).type()
        t = dict(t)
        t["name"] = name
        return t


def parse_type(types: Types, text: str) -> dict:
    p = Parser(types, tokens(text))
    t = p.type()
    return t


def size_of(t: dict) -> int:
    k = t["k"]
    if k in ("int", "bool", "char"):
        return t["size"]
    if k == "string":
        return t["n"] + 1
    if k == "array":
        return (t["hi"] - t["lo"] + 1) * size_of(t["elem"])
    if k == "record":
        return sum(size_of(ft) for _n, ft in t["fields"])
    if k == "set":
        return t["hi"] // 8 - t["lo"] // 8 + 1
    if k == "ptr":
        return 4
    if k == "enum":
        return 1
    if k == "sub":
        return 1 if (t["lo"] >= 0 and t["hi"] <= 255) or (t["lo"] >= -128 and t["hi"] <= 127) else 2
    raise DGroupError("size of %s" % t.get("why", k))


# --- literals ----------------------------------------------------------------------------------------
def pascal_string(b: bytes) -> str:
    if not b:
        return "''"
    out, run = [], ""
    for c in b:
        if 32 <= c < 127:
            run += chr(c) if chr(c) != "'" else "''"
        else:
            if run:
                out.append("'%s'" % run)
                run = ""
            out.append("#%d" % c)
    if run:
        out.append("'%s'" % run)
    return "".join(out)


MAX_COL = 118                    # Turbo Pascal's line limit is 127; keep clear of it


def literal(t: dict, data: bytes, col: int = 0, depth: int = 0) -> str:
    """The typed-constant value of `data` as type `t`; raises DGroupError for what cannot be written.
    `col` is the column the literal starts at (a one-line form must fit), `depth` the nesting."""
    k = t["k"]
    if len(data) != size_of(t):
        raise DGroupError("size mismatch")
    if k == "int":
        return str(int.from_bytes(data, "little", signed=t["signed"]))
    if k == "bool":
        if data[0] > 1:
            raise DGroupError("Boolean out of range")
        return "True" if data[0] else "False"
    if k == "char":
        c = data[0]
        return "'%s'" % chr(c) if 32 <= c < 127 and chr(c) != "'" else "#%d" % c
    if k == "string":
        n = data[0]
        if n > t["n"] or any(data[1 + n:]):
            raise DGroupError("string with stale bytes after its end")
        return pascal_string(data[1:1 + n])
    if k == "array":
        es = size_of(t["elem"])
        count = t["hi"] - t["lo"] + 1
        sub = [literal(t["elem"], data[i * es:(i + 1) * es], col + 1, depth + 1) for i in range(count)]
        one = "(" + ", ".join(sub) + ")"
        if col + len(one) <= MAX_COL and "\n" not in one:
            return one
        pad = " " * (6 + 2 * depth)
        scalar = t["elem"]["k"] in ("int", "bool", "char")
        if scalar:
            lines, cur = [], ""
            for p in sub:
                piece = p + ", "
                if len(pad) + len(cur) + len(piece) > MAX_COL - 4 and cur:
                    lines.append(cur.rstrip())
                    cur = ""
                cur += piece
            lines.append(cur.rstrip().rstrip(","))
            return "(\n" + pad + ("\n" + pad).join(lines) + ")"
        return "(\n" + pad + (",\n" + pad).join(sub) + ")"
    if k == "record":
        parts, o = [], 0
        for nm, ft in t["fields"]:
            s_ = size_of(ft)
            parts.append("%s: %s" % (nm, literal(ft, data[o:o + s_], col + len(nm) + 3, depth + 1)))
            o += s_
        one = "(" + "; ".join(parts) + ")"
        if col + len(one) <= MAX_COL and "\n" not in one:
            return one
        pad = " " * (6 + 2 * depth)
        return "(\n" + pad + (";\n" + pad).join(parts) + ")"
    if k == "set":
        base = t["lo"] // 8
        elems = [base * 8 + i for i in range(len(data) * 8) if data[i // 8] >> (i % 8) & 1]
        if any(e < t["lo"] or e > t["hi"] for e in elems):
            raise DGroupError("set bits outside its range")
        chars = t["lo"] >= 0 and t["hi"] < 256
        return "[" + ", ".join(("'%s'" % chr(e) if 32 <= e < 127 and chr(e) != "'" else "#%d" % e) if chars else str(e)
                               for e in elems) + "]"
    if k == "ptr":
        if any(data):
            raise DGroupError("non-nil pointer")
        return "nil"
    if k == "enum":
        raise DGroupError("enumeration")
    if k == "sub":
        return str(int.from_bytes(data, "little", signed=t["lo"] < 0))
    raise DGroupError("cannot write %s" % t.get("why", k))


def raw_bytes(data: bytes) -> str:
    rows = ["$%02X" % b for b in data]
    lines = [", ".join(rows[i:i + 16]) for i in range(0, len(rows), 16)]
    return "(\n      " + (",\n      ").join(lines) + ")"


def trailing_comment(line: str, trailing: str, out: list[str]) -> None:
    """Add the declaration `line` and its same-line comment; a comment that would make the line too long
    goes on the line above."""
    if not trailing:
        out.append(line)
    elif len(line) + 2 + len(trailing) <= MAX_COL + 6:
        out.append(line + "  " + trailing)
    else:
        out.append("  " + trailing.strip())
        out.append(line)


# --- offsets and sizes -------------------------------------------------------------------------------
def dseg_offsets() -> dict[str, int]:
    d = tomllib.loads((ROOT / "re/dseg.toml").read_text())
    return {g["name"].upper(): g["offset"] for g in d.get("global", [])}


def offset_of(name: str, dseg: dict[str, int]) -> int | None:
    m = re.fullmatch(r"ds([0-9A-Fa-f]{4})", name, re.I)
    if m:
        return int(m.group(1), 16)
    return dseg.get(name.upper())


def probe_sizes(items: list[Item], poolvars_text: str, work: Path) -> dict[str, int]:
    """SizeOf of every declared name, from the compiler itself: a program with a typed constant of the
    sizes, read back from the linked image."""
    ver = tp.pinned_version()
    bin_dir = tp.TC / ver / "BIN"
    for f in ("TPC.EXE", "TURBO.TPL"):
        shutil.copy(bin_dir / f, work / f)
    (work / "POOLVARS.PAS").write_text("{$D-,L-}\r\n" + poolvars_text)
    names = [it.name for it in items]
    body = ",\n  ".join("SizeOf(%s)" % n for n in names)
    (work / "SIZES.PAS").write_text("{$D-,L-}\r\nprogram Sizes;\nuses POOLVARS;\nconst\n  SizeTable: array[0..%d] of Word = (\n  %s);\n"
                                    "begin\n  ExitCode := SizeTable[0];\nend.\n" % (len(names) - 1, body))
    kind, emu = tp.find_emulator(None)
    log = tp.run_tpc(kind, emu, work, ["/B", "/GD", "SIZES.PAS"])
    exe, mapf = tp.ci(work, "SIZES.EXE"), tp.ci(work, "SIZES.MAP")
    if exe is None or mapf is None or "Error" in log:
        raise DGroupError("size probe failed to compile:\n%s" % "\n".join(l for l in log.splitlines() if "Error" in l or "error" in l))
    img, _rel = tp.read_mz(exe)
    segs, pubs = tp.read_map(mapf)
    data_start = segs["DATA"][0]
    off = pubs["SIZETABLE"][1]
    out = {}
    for i, n in enumerate(names):
        a = data_start + off + 2 * i
        out[n] = img[a] | (img[a + 1] << 8)
    return out


# --- the layout --------------------------------------------------------------------------------------
class Cell:
    def __init__(self, start: int, end: int):
        self.start, self.end = start, end
        self.primary: Item | None = None     # the object that is exactly this cell
        self.views: list[Item] = []          # objects `absolute` on this cell

    @property
    def size(self) -> int:
        return self.end - self.start


def plan(items: list[Item], image: bytes, dseg: dict[str, int], passthrough: list[Item]) -> tuple[list[Cell], list[Cell], list[str]]:
    """Cells of the initialised region and of the variables region, and the problems found. A view on a
    library variable (`absolute HeapEnd`) needs no cell: it goes to `passthrough` unchanged."""
    problems: list[str] = []
    # an object in the Overlay unit's own constants (DS:43DC..43EB) is a view of that unit's variable
    lib_ranges = ((CONST_END, SYSTEM_BLOCK, "the Overlay unit's constants"),
                  (LIBRARY_VARS, INPUT_VAR, "the Crt unit's variables"))
    for it in items:
        for lo, hi, what in lib_ranges:
            if it.absolute is None and it.offset is not None and lo <= it.offset < hi:
                lib = next((nm for nm, off in dseg.items() if off == it.offset and off >= CONST_END), None)
                if lib is None:
                    problems.append("%s at DS:%04X is inside %s but names no variable of it (re/dseg.toml)" % (
                        it.name, it.offset, what))
                else:
                    it.absolute = {n.lower(): n for n in LIBRARY_NAMES}.get(lib.lower(), lib)
    objects = [it for it in items if it.absolute is None]
    views = [it for it in items if it.absolute is not None]
    byoff: dict[int, list[Item]] = defaultdict(list)
    for o in objects:
        if o.offset is None:
            problems.append("%s: no original offset" % o.name)
            continue
        byoff[o.offset].append(o)
    cuts = sorted(byoff)
    const_cuts = [c for c in cuts if c < CONST_END]
    var_cuts = [c for c in cuts if c >= VARS_START]
    for c in cuts:
        if CONST_END <= c < VARS_START:
            problems.append("object at DS:%04X inside the System block: %s" % (c, ", ".join(o.name for o in byoff[c])))
        if c < FIRST_CONST:
            problems.append("object at DS:%04X below the first typed constant (DS:%04X): %s" % (
                c, FIRST_CONST, ", ".join(o.name for o in byoff[c])))
        if c >= LIBRARY_VARS:
            problems.append("object at DS:%04X inside the library variables: %s" % (c, ", ".join(o.name for o in byoff[c])))

    def cells_for(cut_list: list[int], lo: int, hi: int) -> list[Cell]:
        pts = sorted(set([lo] + [c for c in cut_list if lo <= c < hi] + [hi]))
        cells = [Cell(a, b) for a, b in zip(pts, pts[1:])]
        return cells

    const_cells = cells_for(const_cuts, FIRST_CONST, CONST_END)
    var_cells = cells_for(var_cuts, VARS_START, LIBRARY_VARS)
    index = {c.start: c for c in const_cells + var_cells}
    for off, group in byoff.items():
        cell = index.get(off)
        if cell is None:
            continue
        # the object that is exactly the cell is the primary; the others are views
        exact = [o for o in group if o.size == cell.size]
        if exact:
            exact.sort(key=lambda o: (re.fullmatch(r"ds[0-9A-Fa-f]{4}", o.name, re.I) is not None, o.name))
            cell.primary = exact[0]
            cell.views.extend(o for o in group if o is not cell.primary)
        else:
            cell.views.extend(group)
    # views on other names (absolute X): X is an object or a view; resolve to its start
    name_off = {n.upper(): it.offset for it in items for n in it.names}
    for v in views:
        tgt = v.absolute.upper()
        off = name_off.get(tgt)
        if off is None and tgt in dseg and dseg[tgt] >= CONST_END:
            passthrough.append(v)
            continue
        if off is None:
            problems.append("%s: absolute %s has no offset" % (v.name, v.absolute))
            continue
        v.offset = off
        cell = index.get(off)
        if cell is None:
            problems.append("%s: absolute %s at DS:%04X is not an object start" % (v.name, v.absolute, off))
            continue
        cell.views.append(v)
    return const_cells, var_cells, problems


def declare(cell: Cell, region: str, types: Types, image: bytes, report: list[str],
            raw_names: list[tuple[str, int]]) -> tuple[str, str]:
    """The Pascal for one cell, and the name of its storage (the views are `absolute` on it)."""
    data = image[DGROUP_BASE + cell.start:DGROUP_BASE + cell.end]
    out: list[str] = []
    prim = cell.primary
    typed = None
    if prim is not None:
        if region == "const":
            try:
                typed = literal(parse_type(types, prim.type_text), data, 0)
            except DGroupError as e:
                report.append("%s (DS:%04X, %d bytes): kept as raw bytes: %s" % (prim.name, cell.start, cell.size, e))
                cell.views.append(prim)
                cell.primary = prim = None
    if prim is not None:
        for c in prim.comments:
            out.append("  " + c.strip())
        if region == "const":
            head_ = "  %s: %s = " % (prim.name, prim.type_text)
            typed = literal(parse_type(types, prim.type_text), data, len(head_))
            trailing_comment(head_ + typed + ";", prim.trailing, out)
        else:
            trailing_comment("  %s: %s;" % (prim.name, prim.type_text), prim.trailing, out)
        return "\n".join(out), prim.name
    cell_name = "ds%04X" % cell.start
    taken = {n.lower() for it in cell.views for n in it.names}
    if cell_name.lower() in taken:
        cell_name = "Raw%04X" % cell.start
        raw_names.append((cell_name, cell.start))
    out.append("  { DS:%04X..%04X: %s }" % (cell.start, cell.end - 1,
                                         ("storage of " + ", ".join(v.name for v in cell.views))
                                         if cell.views else "no declared object"))
    if region == "const":
        out.append("  %s: array[0..%d] of Byte =\n    %s;" % (cell_name, cell.size - 1, raw_bytes(data)))
    else:
        out.append("  %s: array[0..%d] of Byte;" % (cell_name, cell.size - 1))
    return "\n".join(out), cell_name


def build(write: bool, out: Path | None) -> int:
    text = compact_poolvars(POOLVARS.read_text())        # idempotent: start from the declarations only
    head, var_text, tail = split_poolvars(text)
    items = parse_var_section(var_text)
    dseg = dseg_offsets()
    types = Types(head)
    for it in items:
        it.offset = offset_of(it.name, dseg)
    with tempfile.TemporaryDirectory(prefix="dgroup-") as td:
        sizes = probe_sizes(items, text, Path(td))
    for it in items:
        it.size = sizes[it.name]
    image, _rel = tp.read_mz(tp.EXE)
    passthrough: list[Item] = []
    const_cells, var_cells, problems = plan(items, image, dseg, passthrough)
    report: list[str] = []
    raw_names: list[tuple[str, int]] = []
    const_out, var_out = [], []
    pending_views: list[tuple[Item, str]] = []      # (view, the name it is `absolute` on)
    declared: set[str] = {n.lower() for n in dseg}   # library variables are known to the units POOLVARS uses
    for region, cells, sink in (("const", const_cells, const_out), ("var", var_cells, var_out)):
        for cell in cells:
            code, storage = declare(cell, region, types, image, report, raw_names)
            sink.append(code)
            declared.add(storage.lower())
            if cell.primary is not None:
                declared.update(n.lower() for n in cell.primary.names)
            for v in cell.views:
                if v is cell.primary:
                    continue
                # an alias the source already declared (`X absolute Y`) stays on Y; every other view
                # sits on its cell's storage
                pending_views.append((v, v.absolute if (v.absolute and v.absolute.lower() not in {
                    n.lower() for n in LIBRARY_NAMES}) else storage))
    view_out: list[str] = []
    while pending_views:
        progress = False
        for item in list(pending_views):
            v, tgt = item
            if tgt.lower() in declared or tgt.lower() in {n.lower() for n in LIBRARY_NAMES}:
                for c in v.comments:
                    view_out.append("  " + c.strip())
                trailing_comment("  %s: %s absolute %s;" % (", ".join(v.names), v.type_text, tgt), v.trailing, view_out)
                declared.update(n.lower() for n in v.names)
                pending_views.remove(item)
                progress = True
        if not progress:
            for v, tgt in pending_views:
                problems.append("%s: absolute %s is not declared before it" % (v.name, tgt))
            break
    for v in passthrough:
        for c in v.comments:
            view_out.append("  " + c.strip())
        trailing_comment("  %s: %s absolute %s;" % (", ".join(v.names), v.type_text, v.absolute),
                         v.trailing, view_out)
    for p in problems:
        print("problem: " + p)
    for r in report:
        print("note: " + r)
    result = head.rstrip("\n") + "\n"
    result += LAYOUT_BEGIN + "\n"
    result += "const\n  { The initialised data of DGROUP, DS:%04X..%04X, in the original's order (the Overlay unit's own\n" \
              "    constants follow it). Every object keeps its name; where another object overlaps it the bytes\n" \
              "    sit in a dsXXXX cell and the objects are `absolute` views of it (tools/re/dgroup.py, playbook 50). }\n" \
              % (FIRST_CONST, CONST_END - 1)
    result += "\n".join(const_out) + "\n"
    result += "var\n  { The variables of DGROUP, DS:%04X..%04X, in the original's order, then the views. }\n" % (
        VARS_START, LIBRARY_VARS - 1)
    result += "\n".join(var_out) + "\n" + "\n".join(view_out) + "\n" + tail
    print("%d objects/views, %d const cells, %d var cells, %d problems, %d raw" % (
        len(items), len(const_cells), len(var_cells), len(problems), len(report)))
    if out:
        out.write_text(result)
    if write and not problems:
        POOLVARS.write_text(result)
        print("wrote %s" % POOLVARS)
    return 1 if problems else 0


# --- the compact form --------------------------------------------------------------------------------
CELL_NAME = re.compile(r"^(?:ds|Raw)[0-9A-Fa-f]{4}$")


def scan_declarations(text: str):
    """Declarations of a const or var section: (comments, names, type, value, absolute, trailing). The
    value is the text after `=` (a typed constant), `absolute` the name after that keyword."""
    out, pending = [], []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        if c.isspace():
            i += 1
            continue
        if c == "{":
            j = text.index("}", i)
            pending.append(text[i:j + 1])
            i = j + 1
            continue
        j, depth = i, 0
        while j < n:
            ch = text[j]
            if ch == "'":
                j += 1
                while j < n and text[j] != "'":
                    j += 1
            elif ch == "{":
                j = text.index("}", j)
            elif ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif ch == ";" and depth == 0:
                break
            j += 1
        decl = text[i:j]
        i = j + 1
        trailing = ""
        k = i
        while k < n and text[k] in " \t":
            k += 1
        if k < n and text[k] == "{":
            e = text.index("}", k)
            if "\n" not in text[i:e]:
                trailing, i = text[k:e + 1], e + 1
        flat = " ".join(re.sub(r"\{[^}]*\}", " ", decl).split())
        m = re.match(r"^([\w\s,]+?)\s*:\s*(.+)$", flat)
        if not m:
            raise DGroupError("cannot read %r" % flat[:60])
        names = [x.strip() for x in m.group(1).split(",")]
        rest, value, absolute = m.group(2), None, None
        # the type ends at the first top-level `=` of a typed constant
        eq = _top_level(rest, "=")
        if eq is not None:
            rest, value = rest[:eq].strip(), rest[eq + 1:].strip()
        else:
            ma = re.match(r"^(.+?)\s+absolute\s+(\w+)$", rest)
            if ma:
                rest, absolute = ma.group(1).strip(), ma.group(2)
        out.append((pending, names, rest, value, absolute, trailing))
        pending = []
    return out


def _top_level(s: str, ch: str) -> int | None:
    depth, i = 0, 0
    while i < len(s):
        c = s[i]
        if c == "'":
            i += 1
            while i < len(s) and s[i] != "'":
                i += 1
        elif c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        elif c == ch and depth == 0:
            return i
        i += 1
    return None


def compact_poolvars(text: str) -> str:
    """The same declarations without the layout: typed constants become variables, the storage cells
    disappear and the views on them become variables of their own. This is what the matcher compiles
    (it compares addresses by name, so the layout does not matter to it, and Turbo Pascal's compiler
    memory is too small for the full model beside every unit). A source that has no layout block is
    returned unchanged."""
    k = text.find(LAYOUT_BEGIN)
    if k < 0:
        return text
    head = text[:k]
    t = re.search(r"^implementation\b", text, re.M)
    body = text[k + len(LAYOUT_BEGIN):t.start()]
    tail = text[t.start():]
    cm = re.search(r"^const\s*$", body, re.M)
    vm = re.search(r"^var\s*$", body, re.M)
    if not cm or not vm:
        raise DGroupError("POOLVARS.PAS: the layout block has no const or var section")
    consts = scan_declarations(body[cm.end():vm.start()])
    variables = scan_declarations(body[vm.end():])
    cells = {names[0] for comments, names, typ, value, absolute, trailing in consts + variables
             if len(names) == 1 and CELL_NAME.match(names[0]) and re.fullmatch(r"array\[0\.\.\d+\] of Byte", typ)
             and any(c.lstrip().startswith("{ DS:") for c in comments)}
    out = ["var"]
    # views by the cell they sit on, so each lands where its cell was: the matcher maps an address that
    # runs past an object to whatever follows it, so the order (and the unnamed bytes between objects,
    # which stay as plain arrays) must be the layout's
    on_cell: dict[str, list] = {}
    for d in variables:
        comments, names, typ, value, absolute, trailing = d
        if absolute in cells:
            on_cell.setdefault(absolute, []).append(d)

    def emit(comments, names, typ, absolute, trailing):
        for c in comments:
            if c.lstrip().startswith(("{ The initialised data of DGROUP", "{ The variables of DGROUP")):
                continue                              # the generator's own section headings
            out.append("  " + c.strip())
        line = "  %s: %s%s;" % (", ".join(names), typ, (" absolute " + absolute) if absolute else "")
        out.append(line + ("  " + trailing if trailing else ""))

    lib = {n.lower() for n in LIBRARY_NAMES}
    for comments, names, typ, value, absolute, trailing in consts + variables:
        name = names[0]
        if absolute in cells:
            continue                                  # emitted with its cell
        if name in cells:
            views = on_cell.get(name, [])
            if not views:                             # unnamed bytes: keep them, they keep the neighbours apart
                emit([c for c in comments if not c.lstrip().startswith("{ DS:")], names, typ, None, trailing)
            for vc, vn, vt, vv, va, vtr in views:
                emit(vc, vn, vt, None, vtr)
            continue
        if absolute and absolute.lower() in lib:
            absolute = None
        emit(comments, names, typ, absolute, trailing)
    return head.rstrip("\n") + "\n" + "\n".join(out) + "\n" + tail


LIBRARY_NAMES = ("OvrResult", "OvrEmsPages", "OvrTrapCount", "OvrLoadCount", "OvrFileMode", "CheckBreak",
                 "CheckEof", "DirectVideo", "CheckSnow", "LastMode", "TextAttr", "WindMin", "WindMax")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--compact", metavar="FILE", help="print the compact form of a layout POOLVARS and stop")
    ap.add_argument("--write", action="store_true", help="rewrite src/POOLVARS.PAS")
    ap.add_argument("--out", help="write the result here instead")
    a = ap.parse_args(argv)
    if a.compact:
        sys.stdout.write(compact_poolvars(Path(a.compact).read_text()))
        return 0
    try:
        return build(a.write, Path(a.out) if a.out else None)
    except DGroupError as e:
        print("dgroup: %s" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main())
