#!/usr/bin/env python3
"""dgroup.py: lay out the data segment of the rebuild from the game's globals (SPEC 8.4, playbook 50).

  .venv/bin/python tools/re/dgroup.py [--write] [--out FILE]
  make dgroup [WRITE=1]

Turbo Pascal allocates a program's data by declaration: first every unit's typed constants (the
initialised part of the image), then System's variable block, then every unit's variables. A global
therefore sits where the original had it only if the source declares the whole data segment, in offset
order, with the initial values of the typed constants. The decompilers modelled each table the code reads
as a `var` (the matcher compares addresses by name, so no layout was needed); this tool turns that model
into a layout that reproduces the original's DGROUP:

  * the declarations of src/POOLVARS.PAS (names, types, comments) are the input; every one keeps its name
    and type;
  * a `cut` is the start offset of each object. The data between two cuts is one storage cell. An object
    that is exactly its cell is declared as itself (a typed constant with its original initial value, or a
    variable); every other object is `absolute` on the storage cell at its start, which is a named
    `dsXXXX` (the matcher resolves it by its offset) holding raw bytes;
  * the initialised region `[FIRST_CONST, SYSTEM_BLOCK)` is typed constants whose values are the original
    image's bytes; the variables region is plain variables up to the end of the game's part (Crt's own
    variables follow, placed by the compiler);
  * the tool checks its own result: it compiles, then every `dsXXXX` must be where its name says.

The input is the original image (poolrad/start-unpack.exe), read at generation time; the output is
ordinary Pascal in src/POOLVARS.PAS. The tool refuses what it cannot place (an object below DS:0002, where
Turbo Pascal puts its own two bytes, two objects that cannot be told apart) and reports it.
"""
from __future__ import annotations

