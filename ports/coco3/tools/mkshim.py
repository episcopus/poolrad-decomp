#!/usr/bin/env python3
"""mkshim.py: write the CMOC shim of c/include/pool.h (step 8.1; a first, mechanical cut of the
CoCo memory model of PORTING-GUIDE 6.2). Usage: mkshim.py ../../c/include/pool.h out/pool.h

The Phase 7 memory model is a 1 MB arena addressed by 32-bit segment:offset far pointers. For a
64 KB CPU the same source reads, with the only changes below:
  farptr           16-bit native pointer held as an integer
  pool_ds          address 0: DGROUP's offsets become absolute addresses
  FPD(T, p)        a plain cast of the 16-bit value to the pointer type
  POOL_LINEAR(p)  the 16-bit value
Everything else (the runtime interface, the typedefs) is kept, so what is measured is the
generated code and nothing else.
"""
import re
import sys

src = open(sys.argv[1]).read()
subs = [
    (r"typedef u32 farptr;[^\n]*", "typedef u16 farptr;                      /* CoCo shim: a native 16-bit pointer */"),
    (r"extern u8 pool_arena\[POOL_ARENA_SIZE\];\n", ""),
    (r"#define pool_ds \(pool_arena \+ POOL_DS_LINEAR\)", "#define pool_ds ((u8 *)0)"),
    (r"#define POOL_FARPTR\(seg, off\)[^\n]*", "#define POOL_FARPTR(seg, off) ((u16)(off))"),
    (r"#define POOL_LINEAR\(p\)[^\n]*", "#define POOL_LINEAR(p) ((u16)(p))"),
    (r"#define FPD\(T, p\)[^\n]*", "#define FPD(T, p) ((T)(p))"),
    (r"void \(\*rtl_proc\(farptr id\)\)\(void\);", "typedef void (*rtl_proc_t)(void);\nrtl_proc_t rtl_proc(farptr id);"),
    (r"u8 \*rtl_str_cat\(u8 \*dst, int n, const u8 \*const parts\[\]\);", "u8 *rtl_str_cat(u8 *dst, int n, ...);   /* CoCo shim: the parts as arguments */"),
    (r"#define POOL_VIDEO\(off\)[^\n]*", "#define POOL_VIDEO(off) ((u8 *)(u16)(off))     /* CoCo shim: the EGA window is not there */"),
    (r"#define POOL_CAP\(n\)[^\n]*", "#define POOL_CAP(n) 32767                       /* CoCo shim: CMOC arrays stop at 32767 */"),
    (r"#define POOL_DS_LINEAR[^\n]*\n", ""),
    (r"#define POOL_ARENA_SIZE[^\n]*\n", ""),
]
# CMOC has no anonymous unions; the register block is only passed to Intr/MsDos.
reg = re.search(r"typedef struct Registers \{.*?\} Registers;", src, re.S)
src = src[:reg.start()] + "typedef struct Registers { u16 AX, BX, CX, DX, BP, SI, DI, DS, ES, Flags; u8 AL, AH, BL, BH, CL, CH, DL, DH; } Registers;" + src[reg.end():]
for pat, rep in subs:
    src, n = re.subn(pat, lambda m, r=rep: r, src)
    if n == 0:
        sys.exit("mkshim: pattern not found: " + pat)
open(sys.argv[2], "w").write("/* generated by tools/mkshim.py from c/include/pool.h: do not edit */\n" + src)
