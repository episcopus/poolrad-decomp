#!/usr/bin/env python3
"""mkplan.py: which DGROUP globals the CoCo keeps in native memory (step 8.5). The game's globals are 34,656 bytes; the
game's 64 KB map has room for about 8 KB of them next to the code. The rest is reached through the data windows (an
accessor call a use). The choice is made from the profiles of the recorded sessions (make prof): references per byte,
the engine's own tables left out. Usage: mkplan.py REPO GEN_DIR BUDGET_BYTES > placement-vm.toml

A global is never split from the globals that overlap it (an absolute variable or a raw view of the same bytes): the
unit of choice is a cluster of overlapping entries."""
import collections
import glob
import re
import sys

repo, gen, budget = sys.argv[1], sys.argv[2], int(sys.argv[3])
ENGINE = {"res05", "res06", "res07", "res09", "ovl28", "ovl32", "ovl34"}
IDLE = {"ReadPromptChoice", "WaitKeyOrTimeout", "WaitHundredths", "ShowTitleScreen", "GameClock", "TimeInHundredths"}

g = []
for l in open(gen + "/globals.txt"):
    p = l.split()
    g.append((int(p[0], 16), int(p[1]), p[2]))
g.sort()
REPLACED = {"res07"}                               # the engine replaces the whole unit: its text names nothing the CoCo build uses
units = {path.split("/")[-1][:-2]: open(path).read() for path in glob.glob(gen + "/*.c") if path.split("/")[-1][:-2] not in REPLACED}
text = "".join(t for u, t in units.items() if u not in ("image", "poolvars"))
text += "".join(open(f).read() for d in ("c/rtl", "c/platform", "c/driver") for f in glob.glob(repo + "/" + d + "/*.c"))
SYSTEM = [(0x4400, 0x30), (0x84F0, 0x218)]
rtl_offs = {int(m.group(1), 16) for m in re.finditer(r"(?:V16|V32|DGS|pool_ds \+)\(?\s*(0x[0-9A-Fa-f]{4})", text)}
allg = sorted(g + [(o, sz, "system%04X" % o) for o, sz in SYSTEM])
allclusters = []
for off, size, name in allg:
    if allclusters and off < allclusters[-1][1]:
        allclusters[-1][1] = max(allclusters[-1][1], off + size)
        allclusters[-1][2].append(name)
    else:
        allclusters.append([off, off + size, [name]])
clusters = [c for c in allclusters
            if any(re.search(r"\b" + re.escape(n) + r"\b", text) for n in c[2]) or any(c[0] <= x < c[1] for x in rtl_offs)]
starts = [c[0] for c in clusters]


def cluster_of(off):
    lo, hi = 0, len(clusters)
    while lo < hi:
        mid = (lo + hi) // 2
        if clusters[mid][0] <= off:
            lo = mid + 1
        else:
            hi = mid
    i = lo - 1
    return i if i >= 0 and clusters[i][0] <= off < clusters[i][1] else None


fn_unit = {}
for path in glob.glob(gen + "/*.c"):
    unit = path.split("/")[-1][:-2]
    if not unit.startswith(("ovl", "res")):
        continue
    for m in re.finditer(r"^(?:static )?[A-Za-z_][\w ]*?[ *](\w+)\([^;{]*\)\s*\n\{", open(path).read(), re.M):
        fn_unit[m.group(1)] = unit

refs = collections.Counter()                      # cluster -> references by game logic (not the engine, not waiting)
eng = collections.Counter()
for path in glob.glob(repo + "/build/prof/*.prof"):
    names = {}
    for line in open(path):
        t = line.split()
        if t[0] == "F":
            names[int(t[1])] = t[2].lstrip("_")
    for line in open(path):
        t = line.split()
        if t[0] != "G":
            continue
        fn = names.get(int(t[1]), "?")
        if fn in IDLE:
            continue
        i = cluster_of(int(t[2]))
        if i is None:
            continue
        (eng if fn_unit.get(fn) in ENGINE else refs)[i] += int(t[3])

CONST_END = 0x43DC
rows = []
for i, (lo, hi, names) in enumerate(clusters):
    size = hi - lo
    rows.append((refs[i] / size, i, lo, size, names, refs[i], eng[i]))
rows.sort(reverse=True)
chosen, used = [], 0
for dens, i, lo, size, names, r, e in rows:
    if r == 0 or any(n.startswith('system') for n in names):
        continue
    if used + size > budget:
        continue
    chosen.append((lo, size, names, r))
    used += size
chosen.sort()
print("# placement-vm.toml: the DGROUP globals kept in native memory (step 8.5). Generated by tools/mkplan.py from the")
print("# recorded sessions' profiles: references by game logic per byte, within a budget of %d bytes (%d used)." % (budget, used))
print("# Every other global is reached through the data windows. A cluster stands for every name that overlaps it.")
print("[native]")
print("clusters = [")
for lo, size, names, r in chosen:
    print('  [0x%04X, %d, "%s"],   # %d refs%s' % (lo, size, names[0], r, " (" + ",".join(names[1:4]) + ")" if len(names) > 1 else ""))
print("]")
