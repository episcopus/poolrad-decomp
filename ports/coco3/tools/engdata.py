#!/usr/bin/env python3
"""engdata.py: the game data the engine tests read from their .DSK (step 8.3), and what they must find in it.
Usage: engdata.py DATA_DIR OUT_DIR      DATA_DIR is the original game folder (poolrad/, never committed)

Writes OUT_DIR/disk/<NAME>.DAX (copies of the files the tests open) and OUT_DIR/expect.h (sizes, checksums and block
tables the C tests compare against, computed here from the files)."""
import os
import shutil
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../tools/re"))
import dax  # noqa: E402

FILES = ["TITLE.DAX", "8X8D1.DAX"]
data_dir, out = sys.argv[1], sys.argv[2]
os.makedirs(out + "/disk", exist_ok=True)
lines = ["/* generated by tools/engdata.py from the original game files: do not edit, do not commit */"]
for name in FILES:
    src = os.path.join(data_dir, name)
    shutil.copy(src, out + "/disk/" + name)
    raw = open(src, "rb").read()
    tag = name.split(".")[0].replace("8X8D1", "T8X8D1")
    lines.append("#define %s_SIZE %dUL" % (tag, len(raw)))
    lines.append("#define %s_SUM16 %du" % (tag, sum(raw) & 0xFFFF))
    lines.append("#define %s_HS %du" % (tag, struct.unpack("<H", raw[:2])[0]))
    for b in dax.read_dax(src):
        if name == "TITLE.DAX" or b["id"] in (201, 202, 203):
            lines.append("#define %s_B%d_RAW %du" % (tag, b["id"], b["raw"]))
            lines.append("#define %s_B%d_PACKED %du" % (tag, b["id"], b["packed"]))
            lines.append("#define %s_B%d_OFFSET %luUL" % (tag, b["id"], b["offset"]))
            unp = dax.unrle(b["data"])
            lines.append("#define %s_B%d_SUM16 %du" % (tag, b["id"], sum(unp) & 0xFFFF))
open(out + "/expect.h", "w").write("\n".join(lines) + "\n")
print("engdata:", ", ".join(FILES), "->", out)
