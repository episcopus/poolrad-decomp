#!/usr/bin/env python3
"""symexport.py: turn an lwlink map of the resident image into an assembly file of absolute
symbols, so that a code bank can be linked against the core without carrying its own copy of
anything (PORTING-GUIDE 3.5, step 2; answers open question Q6: lwlink resolves a reference
to a symbol in a `constant` section of an earlier object, no library involved).

  symexport.py core.map out.asm [bank1.o bank2.o ...]

With bank objects: export exactly the symbols those objects reference and do not define, and
fail if the core does not provide one (an unresolved reference would otherwise show up as a
link error much later). Without: export every global symbol of the map except the linker's
synthetic ones, local labels and CMOC's per-object bookkeeping symbols.
A name defined at two different addresses in the map is not exported.
"""
import re
import subprocess
import sys

SKIP_PREFIX = ("funcend_", "funcsize_", "bss_", "string_literals_", "s_", "l_")
LOCAL_LABEL = re.compile(r"^[LS]\d{5}$")  # CMOC's per-object branch and string labels
LINE = re.compile(r"^Symbol: (\S+) \((.*)\) = ([0-9A-Fa-f]+)\s*$")
EXT_REF = re.compile(r"\bES=([^\s)]+)")  # also inside expressions: ( I16=-15 ES=MUL16 ... )
EXPORTED = re.compile(r"^\s+(\S+)=[0-9A-Fa-f]+\s*$")


def read_map(map_path):
    syms, conflicts = {}, set()
    for line in open(map_path, encoding="latin-1"):
        m = LINE.match(line)
        if not m:
            continue
        name, obj, addr = m.group(1), m.group(2), int(m.group(3), 16)
        if obj == "<synthetic>" or "@" in name or "\\" in name \
                or name.startswith(SKIP_PREFIX) or LOCAL_LABEL.match(name):
            continue
        if name in syms and syms[name] != addr:
            conflicts.add(name)
        syms[name] = addr
    for name in conflicts:
        del syms[name]
        print(f"symexport: {name} has several addresses, not exported", file=sys.stderr)
    return syms


def wanted_by(objects):
    """Names the objects reference but none of them defines."""
    refs, defs = set(), set()
    for obj in objects:
        out = subprocess.run(["lwobjdump", obj], check=True, capture_output=True,
                             text=True).stdout
        in_exports = False
        for line in out.splitlines():
            if line.startswith("SECTION"):
                in_exports = False
            elif line.strip() == "Exported symbols":
                in_exports = True
            elif line.strip() in ("Incomplete references", "Local symbols"):
                in_exports = False
            elif in_exports:
                m = EXPORTED.match(line)
                if m:
                    defs.add(m.group(1))
            for m in EXT_REF.finditer(line):
                refs.add(m.group(1))
    return refs - defs


def main(map_path, out_path, *objects):
    syms = read_map(map_path)
    if objects:
        need = wanted_by(objects)
        missing = sorted(n for n in need if n not in syms)
        if missing:
            sys.exit("symexport: the core does not provide: " + ", ".join(missing))
        syms = {n: syms[n] for n in need}
    with open(out_path, "w") as f:
        f.write(f"* generated by tools/symexport.py from {map_path}: do not edit\n")
        f.write("\tSECTION\t_constants,constant\n")  # lwlink does not relocate these
        for name in sorted(syms):
            f.write(f"{name}\tEQU\t${syms[name]:04X}\n")
            f.write(f"\tEXPORT\t{name}\n")
        f.write("\tENDSECTION\n")
    print(f"symexport: {len(syms)} symbols -> {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:])
