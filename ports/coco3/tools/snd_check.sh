#!/bin/bash
# snd_check.sh: build probes/snd_ref.c with clang (the CoCo driver and backend on the host, the GIME timer modelled) and check it
# against the oracle (tools/snd_check.py): the speaker events of the golden sound-driver, the tone arithmetic, the clock.
set -e
cd "$(dirname "$0")/.."
B=build/snd
mkdir -p $B
F="-O1 -Wall -Wno-unused-function -DSND_HOST"
clang $F -Dsnd_want_tone=drv_want_tone -Dsnd_want_off=drv_want_off -Dsnd_end=drv_end -c src/snd/snd_driver.c -o $B/driver.o
clang $F -DDriverTick=ref_tick -c src/snd/snd_core.c -o $B/core.o
clang -O1 -Wall -c probes/snd_ref.c -o $B/ref.o
clang $B/driver.o $B/core.o $B/ref.o -o $B/snd_ref
if [ "${1:-}" = expect ]; then
  # the checksums of the driver's calls, per tune, for the engine test t_snd (the 6809 must make the same calls)
  mkdir -p build/eng
  { echo "/* generated by tools/snd_check.sh expect from probes/snd_ref.c digests: the checksum of the speaker calls of each tune's first 237 ticks */"
    echo "static const u16 snd_expect[20] = {"
    $B/snd_ref digests | awk '$1 != "B" {printf "%s%s", sep, $2; sep=", "} END {print ""}'
    echo "};"
    echo "/* the backend's answer for edge divisors: divisor, interrupts per toggle, GIME units per interrupt */"
    echo "#define SND_NBACKEND $($B/snd_ref digests | grep -c '^B')"
    echo "static const u16 snd_backend[][3] = {"
    $B/snd_ref digests | awk '$1 == "B" {printf "%s{%s, %s, %s}", sep, $2, $3, $4; sep=",\n"} END {print ""}'
    echo "};"; } > build/eng/snd_expect.h
  exit 0
fi
exec python3 -I tools/snd_check.py "$@"
