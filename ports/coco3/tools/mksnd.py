#!/usr/bin/env python3
"""mksnd.py: write src/snd/snd_driver.c, the CoCo's sound driver (step 8.8), from c/driver/res03_driver.c.

  python3 tools/mksnd.py [--check]

The driver of the host build (a port of the original's RES03.ASM, proven against the oracle's hardware trace, tools/c/sound_check.py) is the
text of the CoCo's: the tune table, the streams, the voice stepper are not rewritten, so what the host proved is what the CoCo runs. These
edits are made, each one asserted (the script stops when the host's text changed under it):

  * the Tandy chip is gone (the port plays the PC speaker's tunes on the CoCo's DAC only): TandyNotes, the Tandy rows of the tune table,
    TandyQuiet and DriverTandyStep; SetTandyTune keeps CurrentTune as the original does and loads nothing;
  * the platform calls become the backend of src/snd/snd_core.c (snd_speaker_set, snd_speaker_off, snd_begin, snd_end);
  * the timer interrupt's body is DriverTick, called by the pump (snd_core.c) once for every 236.7 Hz tick the FIRQ counted;
  * the variables are the fields of a block (SndState, snd.h) reached through snd_state: a bank holds no writable variables.

--check compares the file on disk with what the script writes (make check-snd, the unit test)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
COCO = os.path.abspath(os.path.join(HERE, ".."))
SRC = os.path.abspath(os.path.join(COCO, "../../c/driver/res03_driver.c"))
OUT = os.path.join(COCO, "src/snd/snd_driver.c")

HEADER = '''/* snd_driver.c: the sound driver of unit RES03 on the CoCo 3, the PC speaker's tunes only (step 8.8). GENERATED by tools/mksnd.py from
 * c/driver/res03_driver.c (the host build, a port of the original's RES03.ASM proven against the oracle's hardware trace): the tune
 * table, the streams and the voice stepper are that file's text. What the script changes:
 *
 *   - the Tandy chip is not supported (no GMC and no Tandy backend, by decision of the user for step 8.8): the Tandy rows of the tune table,
 *     TandyNotes, TandyQuiet and DriverTandyStep are gone and SetTandyTune keeps CurrentTune as the original does;
 *   - the PC speaker is the CoCo's 6 bit DAC: snd_want_tone(divisor, gate bits) and snd_want_off() are snd_core.c's, which note what the tick wants and let the pump set it in the hardware, turning the
 *     PIT divisor into the GIME timer's reload and let the FIRQ write the square wave to the DAC (src/engine/snd.asm);
 *   - the timer interrupt's body, TimerHandler, is DriverTick: the FIRQ only counts, the pump (snd_core.c, called from the clock and the
 *     keyboard poll) runs DriverTick for every 236.7 Hz tick that has passed;
 *   - the variables are fields of the block snd_state points to (SndState in snd.h): a bank holds no variables, the block is in the
 *     mapped heap.
 * Read the host file for the commentary on the format of the streams. Compiled by CMOC into the sound bank (and into the engine test
 * t_snd) and by clang for the reference run (probes/snd_ref.c). */
#include "snd.h"
'''

VARS = '''/* ---- the driver's variables: fields of the block snd_state points to (snd.h) ---- */
#define VoiceMem (snd_state->voices)
#define SpeakerVoices (VoiceMem)
#define InService (snd_state->in_service)
#define VoicesLeft (snd_state->voices_left)
#define CurrentTune (snd_state->current_tune)
#define CurrentVoice (snd_state->current_voice)
#define VoiceBase (snd_state->voice_base)
#define NoteTable (snd_state->note_table)
#define ReturnPtr (snd_state->return_ptr)
#define VoiceTune (snd_state->voice_tune)
#define OutputOn (snd_state->output_on)
#define LoudestVoice (snd_state->loudest_voice)

'''


def cut(text, start, end, repl="", inclusive_end=False):
    """Replace text from the first `start` through (excluding or including) the next `end` after it."""
    i = text.index(start)
    j = text.index(end, i + len(start))
    if inclusive_end:
        j += len(end)
    return text[:i] + repl + text[j:]


def rep(text, old, new, count=1):
    assert text.count(old) == count, "mksnd: %r occurs %d times, expected %d" % (old[:60], text.count(old), count)
    return text.replace(old, new)


def generate():
    t = open(SRC).read()
    # 1. the file header and includes: ours
    i = t.index('#include "game.h"')
    j = t.index("/* ---- voice record fields")
    t = HEADER + "\n" + t[j:]
    # 2. enums: the timer constants are the backend's
    t = rep(t, "  TuneRows = 21,                       /* tunes 0..20; row 0 is silence */\n  NoteTableSize = 12,\n"
               "  TimerDivisor = 5041,                 /* 65536 / 13: 236.7 Hz, 13 times the BIOS rate */\n"
               "  TimerStopped = 0xFFFF                /* what StopSoundTimer writes to channel 0 */\n",
            "  TuneRows = 21,                       /* tunes 0..20; row 0 is silence */\n  NoteTableSize = 12\n")
    t = rep(t, "typedef u16 Voice;                     /* a voice record: VoiceWords words */\n", "")   # snd.h has it
    # 3. the note tables: the speaker's only
    t = cut(t, "static const u16 TandyNotes[12] = {", "};\n", "", True)
    t = rep(t, "\n\n/* The tune table", "\n/* The tune table")
    t = rep(t, "(TandyNotes at 0x0370) the same periods scaled to 16 bits (the chip takes the value >> 6). Only the\n   dead note-event path reads them. */",
            "(TandyNotes at 0x0370) the same periods scaled to 16 bits (the chip takes the value >> 6). Only the\n   dead note-event path reads them. The Tandy table is not on the CoCo. */")
    # 4. the tune table: 21 rows
    t = rep(t, "static const u16 TuneTable[2 * 21 * 4] = {", "static const u16 TuneTable[21 * 4] = {")
    t = rep(t, "  0x0BCC, 0x0000, 0x0000, 0x0000,  /* speaker tune 20 */\n", "  0x0BCC, 0x0000, 0x0000, 0x0000   /* speaker tune 20 */\n")
    k = t.index("  0x0FE8, 0x0FE8, 0x0FE8, 0x0FE8,  /* Tandy tune 0 */")
    e = t.index("/* Tandy tune 20 */\n};", k)
    t = t[:k] + t[e + len("/* Tandy tune 20 */\n"):]
    t = rep(t, "The tune table: row Tune holds the stream pointers of voices 0..3 (0 = no stream). 21 rows for the PC speaker,\n   then 21 for the Tandy chip (SpeakerTunes at 0x0388 and TandyTunes at 0x0430 in RES03.ASM).",
            "The tune table: row Tune holds the stream pointers of voices 0..3 (0 = no stream). 21 rows for the PC speaker\n   (SpeakerTunes at 0x0388 in RES03.ASM; the 21 Tandy rows that follow it there are not on the CoCo).")
    # 5. the variables
    a = t.index("/* ---- the driver's variables (RES03.ASM")
    b = t.index("/* A byte or word of SoundData")
    t = t[:a] + VARS + t[b:]
    # 6. the Tandy steppers
    t = cut(t, "/* Attenuation 15 on all four channels. */", "/* 08AE:13EA TimerHandler", "")
    # 7. the speaker's hardware calls
    t = rep(t, "platform_speaker_set(", "snd_want_tone(")
    t = rep(t, "  platform_speaker_off();\n}\n\n/* 08AE:13EA", "  snd_want_off();\n}\n\n/* 08AE:13EA")
    # 8. the timer interrupt body
    t = rep(t, "/* 08AE:13EA TimerHandler (INT 08h): step both devices unless the handler is already running. */\nstatic void TimerHandler(void)\n{\n"
               "  if (InService == 0) {\n    InService = 1;\n    DriverSpeakerStep();\n    DriverTandyStep();\n    InService = 0;\n  }\n}\n",
            "/* 08AE:13EA TimerHandler (INT 08h), here the body of one 236.7 Hz tick: step the speaker's voices unless the driver is already\n"
            "   running (LoadTune holds InService). The pump calls it. */\nvoid DriverTick(void)\n{\n"
            "  if (InService == 0) {\n    InService = 1;\n    DriverSpeakerStep();\n    InService = 0;\n  }\n}\n")
    # 9. start and stop of the timer: the backend's
    a = t.index("/* 08AE:137C StartSoundTimer.")
    b = t.index("/* SetSpeakerTune/SetTandyTune")
    t = t[:a] + ('/* 08AE:137C StartSoundTimer. The original hooked INT 08h and reloaded PIT channel 0 with 5041 (236.7 Hz): the backend starts the\n'
                 '   GIME timer, which counts the ticks and plays the tone. */\n'
                 'void StartSoundTimer(void)\n{\n  snd_begin();\n}\n\n'
                 '/* 08AE:13B1 StopSoundTimer. Unhook the timer, close the speaker gate (the backend stops the timer and silences the DAC). */\n'
                 'void StopSoundTimer(void)\n{\n  snd_end();\n}\n\n') + t[b:]
    # 10. LoadTune: one device
    t = rep(t, "static void LoadTune(Voice *voices, int device, u16 tune)", "static void LoadTune(Voice *voices, u16 tune)")
    t = rep(t, "  unsigned index = (unsigned)device * (TuneRows * 4) + row;\n", "  unsigned index = row;\n")
    t = rep(t, "index < 2 * TuneRows * 4 ? TuneTable[index] : 0", "index < TuneRows * 4 ? TuneTable[index] : 0")
    t = rep(t, "  LoadTune(SpeakerVoices, 0, tune);", "  LoadTune(SpeakerVoices, tune);")
    t = rep(t, "/* 08AE:17AE SetTandyTune(Tune: Word). */\nvoid SetTandyTune(u16 tune)\n{\n  LoadTune(TandyVoices, 1, tune);\n}\n",
            "/* 08AE:17AE SetTandyTune(Tune: Word). The Tandy voices are not on the CoCo: only CurrentTune, which both devices share, is set\n"
            "   (PlaySound(SoundStop) and SoundQuiet call it before SetSpeakerTune; the second call decides). */\n"
            "void SetTandyTune(u16 tune)\n{\n  CurrentTune = tune;\n}\n")
    # CMOC multiplies two bytes in a byte: the note event path (no shipped tune uses it) widens its product as the host's C does
    t = rep(t, "(u16)(tempo * DataByte((u16)(ev + 1)))", "(u16)((u16)tempo * DataByte((u16)(ev + 1)))")
    # CMOC shifts a byte as a byte: a byte shifted by 8 is zero. The host's C promotes to int first.
    t = rep(t, "(u16)(DataByte(p) | (DataByte((u16)(p + 1)) << 8))", "(u16)(DataByte(p) | ((u16)DataByte((u16)(p + 1)) << 8))")
    t = rep(t, "ax = (u16)(DataByte(ax) << 8);", "ax = (u16)((u16)DataByte(ax) << 8);")
    # 11. the state block is allocated by the first call into the driver
    t = rep(t, "void StartSoundTimer(void)\n{\n  snd_begin();", "void StartSoundTimer(void)\n{\n  SND_ENSURE();\n  snd_begin();")
    t = rep(t, "void StopSoundTimer(void)\n{\n  snd_end();", "void StopSoundTimer(void)\n{\n  SND_ENSURE();\n  snd_end();")
    t = rep(t, "void SetSpeakerTune(u16 tune)\n{\n", "void SetSpeakerTune(u16 tune)\n{\n  SND_ENSURE();\n")
    t = rep(t, "void SetTandyTune(u16 tune)\n{\n", "void SetTandyTune(u16 tune)\n{\n  SND_ENSURE();\n")
    t = rep(t, "void SetSoundOutput(u16 enabled)\n{\n", "void SetSoundOutput(u16 enabled)\n{\n  SND_ENSURE();\n")
    assert "Tandy" not in re.sub(r"/\*.*?\*/", "", t, flags=re.S).replace("SetTandyTune", ""), "a Tandy name is left in the code"
    assert "platform_" not in t and "sound_trace" not in t
    return t


def main():
    text = generate()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            print("snd_driver.c is not what tools/mksnd.py writes from c/driver/res03_driver.c")
            sys.exit(1)
        print("snd_driver.c is current")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(text)
    print("wrote %s (%d lines)" % (os.path.relpath(OUT, COCO), text.count("\n")))


if __name__ == "__main__":
    main()
